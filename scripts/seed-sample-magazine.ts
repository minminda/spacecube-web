/** 독자가 읽는 글자(본문 · 캡션 · 인용 · 문답 · 공간 메모) — 분량 확인용 */
function readableText(b: unknown): string {
  if (typeof b === "string") return b;
  if (Array.isArray(b)) return b.map(readableText).join("");
  if (b && typeof b === "object") {
    return Object.entries(b as Record<string, unknown>)
      .filter(([k]) => ["text", "caption", "cite", "title", "note", "q", "a", "items", "images", "image"].includes(k))
      .map(([, v]) => readableText(v))
      .join("");
  }
  return "";
}

/* ── 실행 ── */
async function main() {
  const spaces = await prisma.editorialSpace.findMany({ where: { isDemo: false }, select: { id: true, slug: true, status: true } });
  const idOf = (slug: string) => {
    const s = spaces.find((x) => x.slug === slug);
    if (!s) throw new Error(`공간을 찾을 수 없어요: ${slug}`);
    if (s.status !== "PUBLISHED") throw new Error(`발행되지 않은 공간: ${slug}`);
    return s.id;
  };

  const backup: unknown[] = [];
  const summary: { doc: string; chars: number; types: string; links: number }[] = [];
  for (const d of DOCS) {
    const resolved = d.blocks.map((b) => (b.type === "SPACE_CARD" ? { type: "SPACE_CARD", spaceId: idOf(String(b.spaceSlug)), ...(b.note ? { note: b.note } : {}) } : b));
    const parsed = parseBlocks(resolved);
    if (!parsed.ok) throw new Error(`${d.kind}/${d.slug}: ${parsed.error}`);
    const chars = parsed.data.reduce((n, b) => n + readableText(b).replace(/\s+/g, "").length, 0);
    summary.push({ doc: `${d.kind}/${d.slug}`, chars, types: [...new Set(parsed.data.map((b) => b.type))].join(" "), links: d.links?.length ?? 0 });

    const model = d.kind === "person" ? prisma.editorialPerson : d.kind === "thought" ? prisma.editorialThought : prisma.editorialCuration;
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const row = await (model as any).findUnique({ where: { slug: d.slug }, select: { id: true, blocks: true, internalNote: true, ...(d.kind === "curation" ? { perspective: true } : {}) } });
    if (!row) throw new Error(`콘텐츠를 찾을 수 없어요: ${d.kind}/${d.slug}`);
    backup.push({ kind: d.kind, slug: d.slug, blocks: row.blocks, internalNote: row.internalNote, perspective: row.perspective });
    if (!APPLY) continue;

    const note = row.internalNote?.includes(MARK) ? row.internalNote : [row.internalNote, MARK].filter(Boolean).join("\n");
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    await (model as any).update({ where: { id: row.id }, data: { blocks: parsed.data, internalNote: note, ...(d.perspective && !row.perspective ? { perspective: d.perspective } : {}) } });

    for (const [i, l] of (d.links ?? []).entries()) {
      const spaceId = idOf(l.slug);
      if (d.kind === "curation") {
        await prisma.editorialCurationSpace.upsert({ where: { curationId_spaceId: { curationId: row.id, spaceId } }, create: { curationId: row.id, spaceId, order: i, note: l.note }, update: { note: l.note } });
      } else if (d.kind === "thought") {
        await prisma.editorialThoughtSpace.upsert({ where: { thoughtId_spaceId: { thoughtId: row.id, spaceId } }, create: { thoughtId: row.id, spaceId, order: i, note: l.note }, update: { note: l.note } });
      } else {
        await prisma.editorialPersonSpace.upsert({ where: { personId_spaceId: { personId: row.id, spaceId } }, create: { personId: row.id, spaceId, order: i, note: l.note }, update: { note: l.note } });
      }
    }
  }

  if (APPLY) {
    const file = join(tmpdir(), `sample-magazine-backup-${Date.now()}.json`);
    writeFileSync(file, JSON.stringify(backup, null, 2));
    console.log(`적용 완료 · 이전 본문 백업: ${file}`);
  } else {
    console.log("미리보기(적용하려면 --apply)");
  }
  console.table(summary);
}

main().finally(() => prisma.$disconnect());
